export function bindAppEventsCore({
  documentObj,
  state,
  bindAppShellEventsCoreFn,
  setStateFn,
  signOutFn,
  auth,
  clearAuthBootstrapSnapshotFn,
  safeStorageObj,
  profileKeyFn,
  avatarKeyFn,
  notificationsKeyFn,
  pushSeenKeyFn,
  pushTokenMetaKeyFn,
  followingKeyFn,
  chatIndexKeyFn,
  storageKeys,
  resetUserScopedStateFn,
  cleanupLeafletFn,
  openGuestAuthPromptFn,
  normalizeAuthModeFn,
  renderFn,
  ensureMenuDataForProfileFn,
  ensureFocusDataForProfileFn,
  bindAppMenuFocusEventsCoreFn,
  saveMenuLayoutToStorageFn,
  openMenuModalFn,
  deleteMenuItemByIdFn,
  triggerMenuDetailOpenFromGestureFn,
  updateShopCartQuantityFn,
  openShopCheckoutFn,
  submitShopCheckoutFn,
  updateShopCheckoutFieldFn,
  focusCache,
  focusCacheKeyFn,
  saveFocusEnabledFn,
  openFocusModalFn,
  deleteFocusItemByIdFn,
  setFocusIndexFn,
  toggleProfilePostMenuFn,
  toggleProfilePostWidthFn,
  deleteProfilePostFn,
  setProfileMenuOpenFn,
  profileMenuBound,
  setProfileMenuBoundFn,
  mapLocateFn,
  bindNotificationsDelegationFn,
  bindAppSettingsProfileEventsCoreFn,
  iconFn,
  saveAccountSettingsFn,
  openLocationPickerFn,
  clearVerifiedMapLocationFn,
  syncNotificationsPushRuntimeFn,
  saveSettingsFn,
  disablePushDeviceRegistrationFn,
  getPushActivationIssueMessageFn,
  saveUserProfileToStorageFn,
  persistPrivateAccountSettingFn,
  uploadAvatarFn,
  openProfileViewFromBusinessFn,
  findPostByIdFn,
  openPostModalFn,
  getProfileViewUnsubFn,
  setProfileViewUnsubFn,
  toggleFollowFn,
  alertFn,
  bindAppChatUploadEventsCoreFn,
  openChatWithProfileFn,
  deleteChatThreadByIdFn,
  setChatThreadArchivedByIdFn,
  closeChatModalFn,
  toggleChatMessageSavedFn,
  toggleChatMessageLikedFn,
  removePendingChatAttachmentFn,
  addChatAttachmentsFn,
  sendChatMessageFn,
  scrollChatMessagesToBottomFn,
  queueMicrotaskFn,
  handleUploadPostFn,
  bindCrmStaffEventsCoreFn,
  openLeadCreatorFn,
  openLeadSettingsViewFn,
  closeLeadSubviewFn,
  saveLeadSettingsFn,
  isLeadInlineCreateViewFn,
  bindLeadInlineCreateEventsCoreFn,
  deleteLeadFromModalFn,
  saveLeadFromModalFn,
  syncLeadDerivedFieldsFn,
  addLeadModalLocationRowFn,
  removeLeadModalLocationRowFn,
  syncLeadModalDraftFromFormFn,
  normalizeLeadLocationsFn,
  createLeadLocationFn,
  parseCoordsFromAddressInputFn,
  getLeadPlusCodeReferenceFn,
  hasLeadLocationCoordsFn,
  getPrimaryLeadLocationFn,
  hydrateLeadGeoFieldsFromCoordsFn,
  refineLeadLocationAddressIndexFn,
  normalizeLeadScopeKeyFn,
  loadLeadsFn,
  openLeadModalFn,
  normalizeCustomerScopeKeyFn,
  loadCustomersFn,
  openCustomerModalFn,
  closeStaffEditorFn,
  openStaffEditorFn,
  syncStaffDerivedEmailFieldFn,
  normalizeCeoCountryFn,
  syncStaffFormFromDomFn,
  saveCeoStaffFromViewFn,
  deleteCeoStaffFromViewFn,
  bindImageFallbacksFn,
  bindCrmAutoLoadObserverFn,
  bindSearchEventsFn
} = {}) {
  const doc = documentObj || null;
  const bindAppShellEvents = typeof bindAppShellEventsCoreFn === "function" ? bindAppShellEventsCoreFn : (() => {});
  const bindAppMenuFocusEvents = typeof bindAppMenuFocusEventsCoreFn === "function" ? bindAppMenuFocusEventsCoreFn : (() => ({}));
  const bindAppSettingsProfileEvents = typeof bindAppSettingsProfileEventsCoreFn === "function" ? bindAppSettingsProfileEventsCoreFn : (() => {});
  const bindAppChatUploadEvents = typeof bindAppChatUploadEventsCoreFn === "function" ? bindAppChatUploadEventsCoreFn : (() => {});
  const bindCrmStaffEvents = typeof bindCrmStaffEventsCoreFn === "function" ? bindCrmStaffEventsCoreFn : (() => {});
  const bindLeadInlineCreateEvents = typeof bindLeadInlineCreateEventsCoreFn === "function" ? bindLeadInlineCreateEventsCoreFn : (() => {});
  const setProfileMenuBound = typeof setProfileMenuBoundFn === "function" ? setProfileMenuBoundFn : (() => {});
  const bindImageFallbacks = typeof bindImageFallbacksFn === "function" ? bindImageFallbacksFn : (() => {});
  const bindCrmAutoLoadObserver = typeof bindCrmAutoLoadObserverFn === "function" ? bindCrmAutoLoadObserverFn : (() => {});
  const bindSearchEvents = typeof bindSearchEventsFn === "function" ? bindSearchEventsFn : (() => {});
  if (!doc || !state) return;

  bindAppShellEvents({
    documentObj: doc,
    state,
    setStateFn,
    signOutFn,
    auth,
    clearAuthBootstrapSnapshotFn,
    safeStorageObj,
    profileKeyFn,
    avatarKeyFn,
    notificationsKeyFn,
    pushSeenKeyFn,
    pushTokenMetaKeyFn,
    followingKeyFn,
    chatIndexKeyFn,
    storageKeys,
    resetUserScopedStateFn,
    cleanupLeafletFn,
    openGuestAuthPromptFn,
    normalizeAuthModeFn,
    renderFn,
    ensureMenuDataForProfileFn,
    ensureFocusDataForProfileFn
  });

  const menuFocusBinding = bindAppMenuFocusEvents({
    documentObj: doc,
    state,
    renderFn,
    saveMenuLayoutToStorageFn,
    openMenuModalFn,
    deleteMenuItemByIdFn,
    triggerMenuDetailOpenFromGestureFn,
    updateShopCartQuantityFn,
    openShopCheckoutFn,
    submitShopCheckoutFn,
    updateShopCheckoutFieldFn,
    focusCache,
    focusCacheKeyFn,
    saveFocusEnabledFn,
    openFocusModalFn,
    deleteFocusItemByIdFn,
    setFocusIndexFn,
    toggleProfilePostMenuFn,
    toggleProfilePostWidthFn,
    deleteProfilePostFn,
    setProfileMenuOpenFn,
    profileMenuBound,
    mapLocateFn,
    bindNotificationsDelegationFn
  });
  setProfileMenuBound(!!menuFocusBinding?.profileMenuBound);

  bindAppSettingsProfileEvents({
    documentObj: doc,
    state,
    setStateFn,
    renderFn,
    iconFn,
    saveAccountSettingsFn,
    openLocationPickerFn,
    clearVerifiedMapLocationFn,
    syncNotificationsPushRuntimeFn,
    saveSettingsFn,
    disablePushDeviceRegistrationFn,
    getPushActivationIssueMessageFn,
    saveUserProfileToStorageFn,
    persistPrivateAccountSettingFn,
    uploadAvatarFn,
    openProfileViewFromBusinessFn,
    findPostByIdFn,
    openPostModalFn,
    getProfileViewUnsubFn,
    setProfileViewUnsubFn,
    toggleFollowFn,
    alertFn
  });

  bindAppChatUploadEvents({
    documentObj: doc,
    state,
    renderFn,
    openChatWithProfileFn,
    deleteChatThreadByIdFn,
    setChatThreadArchivedByIdFn,
    closeChatModalFn,
    toggleChatMessageSavedFn,
    toggleChatMessageLikedFn,
    removePendingChatAttachmentFn,
    addChatAttachmentsFn,
    sendChatMessageFn,
    scrollChatMessagesToBottomFn,
    queueMicrotaskFn,
    handleUploadPostFn
  });

  bindCrmStaffEvents({
    documentObj: doc,
    state,
    renderFn,
    openLeadCreatorFn,
    openLeadSettingsViewFn,
    closeLeadSubviewFn,
    saveLeadSettingsFn,
    isLeadInlineCreateViewFn,
    bindLeadInlineCreateEventsFn: () => bindLeadInlineCreateEvents({
      documentObj: doc,
      state,
      renderFn,
      deleteLeadFromModalFn,
      saveLeadFromModalFn,
      syncLeadDerivedFieldsFn,
      addLeadModalLocationRowFn,
      removeLeadModalLocationRowFn,
      syncLeadModalDraftFromFormFn,
      openLocationPickerFn,
      normalizeLeadLocationsFn,
      createLeadLocationFn,
      parseCoordsFromAddressInputFn,
      getLeadPlusCodeReferenceFn,
      hasLeadLocationCoordsFn,
      getPrimaryLeadLocationFn,
      hydrateLeadGeoFieldsFromCoordsFn,
      refineLeadLocationAddressIndexFn
    }),
    normalizeLeadScopeKeyFn,
    loadLeadsFn,
    openLeadModalFn,
    normalizeCustomerScopeKeyFn,
    loadCustomersFn,
    openCustomerModalFn,
    closeStaffEditorFn,
    openStaffEditorFn,
    syncStaffDerivedEmailFieldFn,
    normalizeCeoCountryFn,
    syncStaffFormFromDomFn,
    openLocationPickerFn,
    saveCeoStaffFromViewFn,
    deleteCeoStaffFromViewFn
  });

  bindImageFallbacks();
  bindCrmAutoLoadObserver();
  bindSearchEvents();
}
